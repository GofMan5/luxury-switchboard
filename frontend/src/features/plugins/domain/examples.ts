const latency: PluginPackage = {
  schema: 1,
  id: 'example.latency-board',
  name: 'Latency board',
  version: '1.0.0',
  author: 'Switchboard examples',
  description: 'A page with live relay metrics and the slowest recent requests, a sidebar badge that counts slow ones, an Alt+L shortcut and two settings. Read-only: it never changes anything.',
  permissions: ['ui:pages', 'ui:commands', 'control:read'],
  settings: [
    {
      key: 'slowMs',
      label: 'Slow request threshold (ms)',
      description: 'Requests that take longer than this are counted as slow and highlighted.',
      type: 'number',
      default: 5000,
      placeholder: '5000',
      min: 100,
      max: 600000,
    },
    {
      key: 'badge',
      label: 'Count slow requests on the sidebar',
      description: 'Shows the number of slow recent requests next to Latency board, even while the page is closed.',
      type: 'toggle',
      default: true,
    },
  ],
  script: lines(
    '// Latency board: one page, read-only data, refreshed by live events.',
    '// The operator tunes it under Plugins → Latency board → Settings.',
    "const PAGE = 'board';",
    'const state = { period: \'24h\', live: true, summary: null, rows: [], available: 0, error: \'\', loading: false };',
    'let visible = false;',
    'let pending = 0;',
    '',
    "const { route } = await switchboard.ui.registerPage({ id: PAGE, title: 'Latency board', icon: 'gauge' });",
    '',
    '// Settings are ready before the script starts; only the operator changes them.',
    "const slowMs = () => switchboard.settings.get('slowMs');",
    "const slowRows = () => state.rows.filter((row) => row.latencyMs > slowMs());",
    '',
    'function ms(value) {',
    "  return typeof value === 'number' && value > 0 ? Math.round(value).toLocaleString() + ' ms' : '—';",
    '}',
    '',
    'function median(values) {',
    '  if (values.length === 0) return 0;',
    '  const sorted = values.slice().sort((a, b) => a - b);',
    '  const middle = Math.floor(sorted.length / 2);',
    '  return sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;',
    '}',
    '',
    'function view() {',
    '  const s = state.summary;',
    '  const latencies = state.rows.map((row) => row.latencyMs).filter((value) => value > 0);',
    '  const slowest = state.rows.slice().sort((a, b) => b.latencyMs - a.latencyMs).slice(0, 12);',
    '  const slow = slowRows().length;',
    '  return {',
    "    type: 'stack',",
    '    children: [',
    "      { type: 'row', align: 'between', children: [",
    "        { type: 'segmented', name: 'period', label: 'History window', value: state.period, options: [",
    "          { value: '24h', label: '24 h' }, { value: '48h', label: '48 h' }, { value: '72h', label: '72 h' },",
    '        ] },',
    "        { type: 'row', gap: 'sm', children: [",
    "          { type: 'toggle', name: 'live', label: 'Live refresh', value: state.live },",
    "          { type: 'button', text: state.loading ? 'Refreshing…' : 'Refresh', action: 'refresh', disabled: state.loading },",
    '        ] },',
    '      ] },',
    "      state.error ? { type: 'text', tone: 'danger', text: state.error } : null,",
    "      { type: 'metrics', items: [",
    "        { label: 'Requests', value: s ? s.requests : '—', detail: s ? s.active + ' active · ' + s.queued + ' queued' : '' },",
    "        { label: 'Success', value: s ? s.successRate.toFixed(1) + '%' : '—', tone: s && s.successRate < 90 ? 'warning' : undefined },",
    "        { label: 'p95 latency', value: ms(s && s.p95Ms), detail: 'live window' },",
    "        { label: 'Median', value: ms(median(latencies)), detail: latencies.length + ' recent requests' },",
    "        { label: 'Throughput', value: s ? s.rpm.toFixed(1) + ' rpm' : '—' },",
    "        { label: 'Slow', value: slow, detail: 'over ' + ms(slowMs()), tone: slow > 0 ? 'warning' : undefined },",
    '      ] },',
    "      { type: 'panel', title: 'Slowest recent requests', subtitle: state.available + ' in the ' + state.period + ' window', children: [",
    "        { type: 'table', empty: 'No requests in this window yet.', columns: [",
    "          { key: 'model', label: 'Model', mono: true },",
    "          { key: 'providerId', label: 'Provider' },",
    "          { key: 'status', label: 'Status', align: 'right', width: 80 },",
    '          // Raw numbers plus a format: the window writes 850 ms, 1.234 s or 2m 05s.',
    "          { key: 'latency', label: 'Latency', format: 'duration', mono: true, width: 110 },",
    "          { key: 'tokens', label: 'Tokens', format: 'number', mono: true, width: 100 },",
    '        ], rows: slowest.map((row) => ({',
    '          id: row.id, model: row.model, providerId: row.providerId, status: row.status || row.state,',
    '          latency: row.latencyMs, tokens: row.totalTokens,',
    '        })) },',
    '      ] },',
    '    ],',
    '  };',
    '}',
    '',
    '// The badge sits next to the page in the sidebar: 1–8 characters, or null to clear it.',
    'async function badge() {',
    '  const slow = slowRows().length;',
    "  const show = switchboard.settings.get('badge') && slow > 0;",
    "  await switchboard.ui.setBadge(PAGE, show ? { text: slow > 99 ? '99+' : String(slow), tone: 'warning' } : null);",
    '}',
    '',
    'async function draw() {',
    '  await switchboard.ui.render(PAGE, view());',
    '  await badge();',
    '}',
    '',
    'async function refresh() {',
    '  state.loading = true;',
    '  await draw();',
    '  try {',
    '    const [summary, recent] = await Promise.all([',
    "      switchboard.control.call('activity.summary'),",
    "      switchboard.control.call('history.recent', { period: state.period, limit: 200 }),",
    '    ]);',
    '    state.summary = summary;',
    '    state.rows = recent.requests || [];',
    '    state.available = recent.available || 0;',
    "    state.error = '';",
    '  } catch (error) {',
    "    state.error = 'Could not load relay data: ' + error.message;",
    '  }',
    '  state.loading = false;',
    '  await draw();',
    '}',
    '',
    '// Live events arrive in bursts; refresh at most every two seconds, and',
    '// only while the page is on screen or the sidebar badge needs the count.',
    'function soon() {',
    "  const needed = visible || switchboard.settings.get('badge');",
    '  if (!state.live || !needed || pending) return;',
    '  pending = setTimeout(() => { pending = 0; refresh(); }, 2000);',
    '}',
    '',
    'switchboard.ui.onEvent(PAGE, (event) => {',
    "  if (event.kind === 'show') { visible = true; refresh(); }",
    "  if (event.kind === 'hide') visible = false;",
    "  if (event.action === 'refresh') refresh();",
    "  if (event.name === 'period') { state.period = event.value; refresh(); }",
    "  if (event.name === 'live') { state.live = event.value; draw(); }",
    '});',
    '',
    '// The operator saved new settings: redraw with the new threshold and badge choice.',
    'switchboard.settings.onChange(() => draw());',
    '',
    '// A palette command with a global shortcut. Another plugin may already hold',
    '// Alt+L; then registering answers "conflict", and the command stays in the',
    '// palette without a key.',
    "const open = { id: 'open', title: 'Open latency board', keywords: ['latency', 'slow', 'p95'] };",
    'try {',
    "  await switchboard.commands.register({ ...open, shortcut: 'Alt+L' }, () => switchboard.navigate(route));",
    '} catch (error) {',
    "  if (error.code !== 'conflict') throw error;",
    "  console.warn(error.message + ' Open latency board has no shortcut.');",
    '  await switchboard.commands.register(open, () => switchboard.navigate(route));',
    '}',
    '',
    "await switchboard.events.on('activity.changed', soon);",
    'await draw();',
    "if (switchboard.settings.get('badge')) refresh();",
  ),
}

const quick: PluginPackage = {
  schema: 1,
  id: 'example.quick-switch',
  name: 'Quick switch',
  version: '1.0.0',
  author: 'Switchboard examples',
  description: 'Palette commands to switch the active provider and start or stop the relay, with a notification for each.',
  permissions: ['ui:commands', 'ui:notify', 'control:read', 'control:write'],
  script: lines(
    '// Quick switch: palette commands that change relay state.',
    '// One command per provider, kept in step with the provider list.',
    'const registered = new Map(); // command id -> provider id',
    '',
    'function commandId(providerId) {',
    "  return 'use.' + providerId.toLowerCase().replace(/[^a-z0-9_.-]+/g, '-').slice(0, 40);",
    '}',
    '',
    'async function syncProviders() {',
    "  const { providers, activeId } = await switchboard.control.call('providers.list');",
    '  const wanted = new Map();',
    '  for (const provider of providers) {',
    '    if (!provider.enabled) continue;',
    '    wanted.set(commandId(provider.id), provider);',
    '  }',
    '  for (const id of registered.keys()) {',
    '    if (!wanted.has(id)) { registered.delete(id); await switchboard.commands.unregister(id); }',
    '  }',
    '  for (const [id, provider] of wanted) {',
    '    registered.set(id, provider.id);',
    '    await switchboard.commands.register({',
    '      id,',
    "      title: (provider.id === activeId ? 'Active provider: ' : 'Switch to ') + provider.name,",
    "      group: 'Providers',",
    "      keywords: ['provider', 'switch', 'activate'],",
    '    }, () => activate(provider));',
    '  }',
    '}',
    '',
    'async function activate(provider) {',
    '  try {',
    "    await switchboard.control.call('providers.activate', { id: provider.id });",
    "    await switchboard.notify({ title: 'Switched to ' + provider.name, tone: 'success' });",
    '  } catch (error) {',
    "    await switchboard.notify({ title: 'Could not switch to ' + provider.name, body: error.message, tone: 'danger' });",
    '  }',
    '}',
    '',
    'async function relay(action) {',
    '  try {',
    "    await switchboard.control.call('relay.' + action);",
    "    await switchboard.notify({ title: action === 'start' ? 'Relay started' : 'Relay stopped', tone: action === 'start' ? 'success' : 'info' });",
    '  } catch (error) {',
    "    await switchboard.notify({ title: 'Relay ' + action + ' failed', body: error.message, tone: 'danger' });",
    '  }',
    '}',
    '',
    "await switchboard.commands.register({ id: 'relay.start', title: 'Start the relay', group: 'Relay', keywords: ['relay', 'start', 'on'] }, () => relay('start'));",
    "await switchboard.commands.register({ id: 'relay.stop', title: 'Stop the relay', group: 'Relay', keywords: ['relay', 'stop', 'off'] }, () => relay('stop'));",
    'await syncProviders();',
    "await switchboard.events.on('providers.changed', () => syncProviders());",
  ),
}

